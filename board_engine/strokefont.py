CELL, ADVANCE = 6.0, 6.0          # glyph height and pen advance per character, in grid units


def text_width(text, height):
    return max(0.0, (len(text) * ADVANCE - 2) * height / CELL)


def text_strokes(text, x, y, height, align='left'):
    """Polylines [(u, v), ...] for `text` with its baseline starting at (x, y), cap height `height` (v up).
    align: 'left' | 'center' | 'right' about x."""
    s = height / CELL
    x0 = x - {'left': 0.0, 'center': 0.5, 'right': 1.0}[align] * text_width(text, height)
    out = []
    for i, ch in enumerate(text):
        if ch == ' ':
            continue
        for stroke in GLYPHS.get(ch.upper(), GLYPHS['?']):
            out.append([(round(x0 + (i * ADVANCE + gx) * s, 4), round(y + gy * s, 4)) for gx, gy in stroke])
    return out
